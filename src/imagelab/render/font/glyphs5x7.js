/**
 * Chuyển bảng glyph thành mask theo dòng.
 *
 * Quy ước bit DÙNG CHUNG cho cả file này lẫn `diacritics.js`:
 *   cột `c` (0..5) ứng với bit `CELL_COLS - 1 - c` — cột trái nhất là bit 5.
 *
 * @returns {Map<string, Uint8Array>} ký tự → mảng 12 mask dòng (mỗi mask 6 bit)
 */
export function buildBaseMasks() {
  const map = new Map();
  for (const [char, rows] of Object.entries(BASE_GLYPHS)) {
    const parts = String(rows).split(',');
    if (parts.length !== GLYPH_H) {
      throw new Error(`Glyph "${char}" phải có đúng ${GLYPH_H} dòng, đang có ${parts.length}.`);
    }
    const mask = new Uint8Array(CELL_ROWS);
    for (let r = 0; r < parts.length; r += 1) {
      const row = parts[r];
      if (row.length !== GLYPH_W || /[^01]/.test(row)) {
        throw new Error(`Glyph "${char}" dòng ${r} phải là ${GLYPH_W} ký tự 0/1, nhận "${row}".`);
      }
      let bits = 0;
      for (let c = 0; c < GLYPH_W; c += 1) {
        if (row[c] === '1') bits |= 1 << (CELL_COLS - 1 - c);
      }
      mask[BASE_OFFSET + r] = bits;
    }
    map.set(char, mask);
  }
  return map;
}
