/**
 * Bảng glyph bitmap gốc 5x7 (ASCII 32..126) — tự vẽ, không copy thư viện ngoài.
 *
 * Mỗi glyph là 7 dòng, mỗi dòng 5 ký tự '0'/'1' (trái → phải).
 * Glyph được đặt vào "ô" cao 12 dòng (xem CELL_ROWS): dòng 0 của bảng nằm ở dòng 4 của ô,
 * chừa 4 dòng phía trên cho dấu mũ/trăng/móc + dấu thanh và 1 dòng phía dưới cho dấu nặng.
 *
 * Quy ước ô (cell) 6 cột × 12 dòng:
 *   - cột 0..4 : thân chữ
 *   - cột 5    : dành riêng cho dấu móc (ơ, ư, Ớ, Ứ…)
 *   - dòng 0..3: vùng dấu (thanh ở 0..1, mũ/trăng ở 2..3 với chữ hoa; thấp hơn với chữ thường)
 *   - dòng 4..10: thân chữ (dòng 10 = chân chữ cái thường/đường cơ sở)
 *   - dòng 11  : dấu nặng (dot below)
 */

